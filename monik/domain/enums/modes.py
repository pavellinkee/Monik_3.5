"""Режимы сканирования Monik.

Режим — это именованный набор настроек одного прохода Level 1: свой
интервал, свой порог, свой набор токенов и свой состав агрегаторов.
Уровни при этом не меняются: Level 1 ищет, Level 2 подтверждает
(``10_LEVEL_1_SCANNER.md`` §95). Режим говорит, **чем** и **как часто**
ищет Level 1, а не **что** делают уровни.

Имена заданы оператором и используются и в конфигурации, и в журнале, и
в уведомлениях: без них два разных прохода в записях неотличимы, и
настройки одного принимались за настройки другого.
"""

from __future__ import annotations

from monik.domain.enums.base import DomainEnum

__all__ = ["ScanMode"]


class ScanMode(DomainEnum):
    """Режим прохода Level 1."""

    #: Основной проход: весь набор токенов и все включённые агрегаторы.
    UR = "ur"
    #: Частый проход по стабильным токенам. Набор определяется меткой
    #: ``usd_stable`` у токена, состав агрегаторов — их собственным
    #: списком режимов.
    FEST = "fest"
